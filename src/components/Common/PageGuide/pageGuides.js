const roleOf = (groups) => {
    if (groups.includes('Закрійник')) return 'cutter';
    if (groups.includes('Швачка') || groups.includes('Швея')) return 'sewer';
    if (groups.includes('Пакувальник')) return 'packer';
    return 'other';
};

/** The guide for a page, or null. */
export const getPageGuide = (pathname, groups) => {
    const role = roleOf(Array.isArray(groups) ? groups : []);
    if (pathname === '/orders') return PRODUCTION_LIST[role];
    if (pathname === '/order') return PRODUCTION_ORDER[role] || null;
    return GUIDES[pathname] || null;
};
